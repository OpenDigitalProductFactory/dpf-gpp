import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,rm,cp,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,dirname} from 'node:path';
import {spawnSync} from 'node:child_process';
import {root,provenance,originalSource} from './source-baseline.mjs';

// Reconstruct only the pinned original test closure, never a runtime package.
const temp=await mkdtemp(join(tmpdir(),'gpp-original-baseline-'));
try{
  for(const entry of provenance.files){const target=join(temp,entry.path);await mkdir(dirname(target),{recursive:true});await writeFile(target,await originalSource(entry));}
  await writeFile(join(temp,'package.json'),JSON.stringify({private:true,type:'module'}));
  for(const dependency of ['typescript','zod','@types/node','undici-types']){
    const target=join(temp,'node_modules',dependency);await mkdir(dirname(target),{recursive:true});await cp(join(root,'node_modules',dependency),target,{recursive:true,dereference:false});
  }
  // Expose original generated bytes for installed-candidate parity. Product code stays unchanged.
  const harness=join(temp,'examples/gpp-toolkit/run.mjs');
  const text=await readFile(harness,'utf8');assert(text.includes('delete result.generatedModule;'));
  await writeFile(harness,text.replace('delete result.generatedModule;','const baselineGeneratedModule = result.generatedModule; const baselineShapeSchema = (await import(pathToFileURL(join(temp,"browser-dist/kernel/gpp/browser.js")).href)).gppShapeJsonSchema(); delete result.generatedModule;').replace('browser: { sourceFiles: seen.size','baselineGeneratedModule, baselineShapeSchema, browser: { sourceFiles: seen.size'));
  const result=spawnSync(process.execPath,[harness],{cwd:temp,env:{...process.env,NODE_PATH:'',NODE_OPTIONS:''},encoding:'utf8',maxBuffer:8*1024*1024});
  assert.equal(result.status,0,`Original behavioral baseline failed:\n${result.stdout}${result.stderr}`);
  process.stdout.write(result.stdout);
}finally{await rm(temp,{recursive:true,force:true});}
